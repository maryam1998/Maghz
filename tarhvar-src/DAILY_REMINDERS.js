export const REMINDERS_PER_DAY = 10;

/* ============================================================
 * گرفتن یادآوری‌های امروز
 * اگر schemaIds داده شود، از بین یادآوری‌های همان طرحواره‌ها
 * اگر نه، از بین یادآوری‌های عمومی
 * ============================================================ */
export function getTodayReminders(schemaIds = null) {
  const now = new Date();
  const dayOfYear = Math.floor(
    (now - new Date(now.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)
  );

  // اگر schemaIds معتبر داده شد، از یادآوری‌های همان طرحواره‌ها استفاده کن
  if (Array.isArray(schemaIds) && schemaIds.length > 0) {
    const pool = [];
    for (const sid of schemaIds) {
      const list = REMINDERS_BY_SCHEMA[sid];
      if (list && list.length) pool.push(...list);
    }
    if (pool.length === 0) {
      return _pick(dayOfYear, GENERAL_REMINDERS, REMINDERS_PER_DAY);
    }
    return _pick(dayOfYear, pool, REMINDERS_PER_DAY);
  }

  // پیش‌فرض: عمومی
  return _pick(dayOfYear, GENERAL_REMINDERS, REMINDERS_PER_DAY);
}

/* ============================================================
 * کمک‌کننده‌ها
 * ============================================================ */
function _pick(dayOfYear, arr, n) {
  if (!arr || arr.length === 0) return [];
  const start = (dayOfYear * 7) % arr.length;
  const result = [];
  for (let i = 0; i < n; i++) {
    result.push(arr[(start + i) % arr.length]);
  }
  return result;
}

export function getAllReminders() {
  return GENERAL_REMINDERS;
}

export function getAllRemindersForSchema(schemaId) {
  return REMINDERS_BY_SCHEMA[schemaId] || [];
}

