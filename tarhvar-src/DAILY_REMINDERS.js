// تعداد یادآوری‌ها در روز
export const REMINDERS_PER_DAY = 10;

// گرفتن ۱۰ یادآوری برای امروز (ثابت در طول یک روز)
export function getTodayReminders() {
  const now = new Date();
  const dayOfYear = Math.floor(
    (now - new Date(now.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)
  );
  const start = (dayOfYear * 7) % ALL_REMINDERS.length;
  const result = [];
  for (let i = 0; i < REMINDERS_PER_DAY; i++) {
    result.push(ALL_REMINDERS[(start + i) % ALL_REMINDERS.length]);
  }
  return result;
}

// همه یادآوری‌ها (برای صفحه اختصاصی)
export function getAllReminders() {
  return ALL_REMINDERS;
}
